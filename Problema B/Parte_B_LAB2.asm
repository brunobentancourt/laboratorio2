.include "m328pdef.inc"

.def temp   = r16
.def dato   = r17
.def delay_val = r21 

.org 0x0000
    rjmp RESET

RESET:
  
    ldi temp, LOW(RAMEND)
    out SPL, temp
    ldi temp, HIGH(RAMEND)
    out SPH, temp

 
    ldi temp, 0xFF
    out DDRD, temp

  
    cbi DDRB, 0        
    cbi DDRB, 1        
    cbi DDRB, 2       
    
    sbi PORTB, 0     
    sbi PORTB, 1     
    sbi PORTB, 2       

    ldi delay_val, 20

MAIN_LOOP:
   
    sbic PINB, 1        
    rjmp CHECK_BTN_DEC
    cpi delay_val, 2      
    breq CHECK_BTN_DEC
    dec delay_val      

CHECK_BTN_DEC:
   
    sbic PINB, 2         
    rjmp CHECK_WAVE
    cpi delay_val, 250  
    breq CHECK_WAVE
    inc delay_val         

CHECK_WAVE:
   
    sbis PINB, 0         
    rjmp MOSTRAR_SENAL11  
    rjmp MOSTRAR_SENAL7  


MOSTRAR_SENAL7:
    ldi ZL, LOW(LUT_SENAL7 * 2)
    ldi ZH, HIGH(LUT_SENAL7 * 2)
    ldi r19, 64

LOOP_S7:
    lpm dato, Z+
    out PORTD, dato
    rcall DELAY
    dec r19
    brne LOOP_S7
    rjmp MAIN_LOOP


MOSTRAR_SENAL11:
    ldi ZL, LOW(LUT_SENAL11 * 2)
    ldi ZH, HIGH(LUT_SENAL11 * 2)
    ldi r19, 0

LOOP_S11:
    lpm dato, Z+
    out PORTD, dato
    rcall DELAY
    dec r19
    brne LOOP_S11
    rjmp MAIN_LOOP


DELAY:
    mov r20, delay_val    
D_LOOP:
    dec r20
    brne D_LOOP
    ret


